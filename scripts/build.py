#!/usr/bin/env python3
"""Build the generated study files from their sources of truth.

    data/insights.json  ->  study/flashcards.csv   (imports straight into Anki)
    insights/*.md + ... ->  dist/ALL-INSIGHTS.md   (one file to feed NotebookLM,
                                                    a Claude Project, Obsidian...)

It also validates insights.json. Run `--check` in CI: it changes nothing and
exits 1 if a generated file is stale, so the bundle can never drift from the
chapters.
"""

from __future__ import annotations

import argparse
import csv
import io
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXIT_OK = 0
EXIT_STALE = 1
EXIT_INVALID = 2

REQUIRED = ("id", "chapter", "title", "eli5", "takeaway", "speaker",
            "concepts", "confidence", "tags", "cards")
CONFIDENCE = {"episode", "episode+verified", "episode+anecdotal"}
CONCEPT = re.compile(r"C(\d+)")
LEDGER_SIZE = 28
BUNDLE_EXTRAS = ("study/cheatsheet.md", "study/critical-lens.md", "SOURCES.md")
SIBLING_LINK = re.compile(r"\]\(([\w.-]+\.md)\)")

HEADER = """# All insights in one file: {title}

> {host} with {guest} · {date} · {url}
>
> Generated by `scripts/build.py` from this repository's chapters, cheat sheet,
> critical lens and sources. Edit those files, not this one.
> Provenance: {provenance}."""


def valid_concept(concept: str) -> bool:
    match = CONCEPT.fullmatch(concept)
    return bool(match) and 1 <= int(match[1]) <= LEDGER_SIZE


def missing_keys(insight: dict) -> list[str]:
    return [key for key in REQUIRED if key not in insight]


def insight_problems(insight: dict, chapters: set[int]) -> list[str]:
    if missing := missing_keys(insight):
        return [f"{insight.get('id', '?')}: missing {', '.join(missing)}"]
    checks = {
        "unknown chapter": insight["chapter"] in chapters,
        "unknown confidence label": insight["confidence"] in CONFIDENCE,
        "needs at least one flashcard": bool(insight["cards"]),
        f"concepts must be C1..C{LEDGER_SIZE}": all(map(valid_concept, insight["concepts"])),
    }
    return [f"{insight['id']}: {message}" for message, ok in checks.items() if not ok]


def chapter_file_problems(chapters: list[dict], root: Path) -> list[str]:
    return [f"missing chapter file {c['file']}" for c in chapters if not (root / c["file"]).exists()]


def duplicate_id_problems(insights: list[dict]) -> list[str]:
    ids = [insight.get("id") for insight in insights]
    return [f"duplicate id {i}" for i in sorted(set(ids)) if ids.count(i) > 1]


def validate(data: dict, root: Path) -> list[str]:
    chapters = {c["number"] for c in data["chapters"]}
    problems = chapter_file_problems(data["chapters"], root) + duplicate_id_problems(data["insights"])
    for insight in data["insights"]:
        problems += insight_problems(insight, chapters)
    return problems


def card_tags(insight: dict) -> str:
    return " ".join(["uncle-bob-ai", f"ch{insight['chapter']:02d}", insight["id"], *insight["tags"]])


def flashcards_csv(data: dict) -> str:
    out = io.StringIO()
    out.write("#separator:Comma\n#html:false\n#tags column:3\n")
    writer = csv.writer(out, lineterminator="\n")
    for insight in data["insights"]:
        source = f" [{insight['id']} · {insight['title']}]"
        for card in insight["cards"]:
            writer.writerow([card["q"], card["a"] + source, card_tags(insight)])
    return out.getvalue()


def glance_table(data: dict) -> str:
    rows = ["## Insights at a glance", "", "| ID | Insight | ELI5 | Takeaway |", "|---|---|---|---|"]
    rows += [f"| {i['id']} | {i['title']} | {i['eli5']} | {i['takeaway']} |" for i in data["insights"]]
    return "\n".join(rows)


def chapter_text(path: Path) -> str:
    # Chapters link to each other by bare file name; from dist/ those links
    # must point back into insights/.
    return SIBLING_LINK.sub(r"](../insights/\1)", path.read_text())


def bundle_markdown(data: dict, root: Path) -> str:
    parts = [HEADER.format(**data["episode"]), glance_table(data)]
    parts += [chapter_text(root / c["file"]) for c in data["chapters"]]
    parts += [(root / extra).read_text() for extra in BUNDLE_EXTRAS]
    return "\n\n---\n\n".join(part.strip() for part in parts) + "\n"


def outputs(data: dict, root: Path) -> dict[Path, str]:
    return {
        root / "study" / "flashcards.csv": flashcards_csv(data),
        root / "dist" / "ALL-INSIGHTS.md": bundle_markdown(data, root),
    }


def write(files: dict[Path, str], root: Path) -> int:
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(root)}")
    return EXIT_OK


def check(files: dict[Path, str], root: Path) -> int:
    stale = [p for p, content in files.items() if not p.exists() or p.read_text() != content]
    for path in stale:
        print(f"stale: {path.relative_to(root)} (run `make build` and commit the result)")
    return EXIT_STALE if stale else EXIT_OK


def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="verify generated files are up to date; write nothing")
    args = parser.parse_args(argv)
    data = json.loads((root / "data" / "insights.json").read_text())
    problems = validate(data, root)
    if problems:
        print("\n".join(["data/insights.json has problems:", *problems]))
        return EXIT_INVALID
    files = outputs(data, root)
    return check(files, root) if args.check else write(files, root)


if __name__ == "__main__":
    sys.exit(main())
